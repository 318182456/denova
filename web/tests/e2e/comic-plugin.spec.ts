import { cp, readFile, readdir } from 'node:fs/promises'
import path from 'node:path'
import { expect, test } from '../support/fixtures'
import { createAndOpenBook, readProjectFile } from '../support/api'

// Cross-repository acceptance uses the actual index example, never a copied
// product fixture that could drift independently from the distributed plugin.
const source = process.env.DENOVA_TEST_COMIC_PLUGIN

test('comic plugin generates, edits, shares references and restores Project content', async ({ page, request, browserDiagnostics }) => {
  test.skip(!source, 'Set DENOVA_TEST_COMIC_PLUGIN to the index comic plugin directory')
  browserDiagnostics.allow(/console.error: Failed to load resource:.*404.*project-content\/file\?path=comic%2Fcomic.json/)
  const book = await createAndOpenBook(request, 'Comic acceptance')
  const sourceDirectory = path.join(book.workspace, 'comic-plugin-source')
  await cp(source!, sourceDirectory, { recursive: true, force: false, errorOnExist: true })
  const linked = await request.post('/api/platform/manage/development/link', { data: { kind: 'plugin', projectId: book.projectId, relativePath: 'comic-plugin-source' } })
  expect(linked.ok(), await linked.text()).toBe(true)
  const development = await linked.json()
  const checked = await request.get(`/api/platform/manage/development/${development.developmentId}/check`)
  expect(checked.ok(), await checked.text()).toBe(true)
  const candidate = await checked.json()
  const installed = await request.post('/api/platform/manage/packages/install', { data: { candidateId: candidate.candidateId, grants: candidate.manifest.permissions.required } })
  expect(installed.ok(), await installed.text()).toBe(true)
  const config = await (await request.get(`/api/platform/manage/projects/${book.projectId}/extensions`)).json()
  const configured = await request.put(`/api/platform/manage/projects/${book.projectId}/extensions`, { data: { expectedRevision: config.revision, extensions: { ...config.extensions, models: { 'index.comic-studio/writer': 'e2e', 'index.comic-studio/image': 'e2e-image' } } } })
  expect(configured.ok(), await configured.text()).toBe(true)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.addInitScript(() => localStorage.setItem('nova:mode', 'plugin:index.comic-studio/studio'))
  await page.goto('/')
  const studio = page.frameLocator('iframe[title="插件界面"]')
  await expect(studio.getByText('从第一话开始', { exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '故事与角色设定', exact: true }).click()
  await studio.getByRole('textbox', { name: '名称', exact: true }).fill('雨夜的末班车')
  await studio.getByRole('textbox', { name: '故事设定', exact: true }).fill('雨夜车站，林夏等待最后一班车。黑白漫画，中文对白。')
  await studio.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { name: '雨夜的末班车' })).toBeVisible()
  await studio.getByRole('button', { name: '新分话', exact: true }).first().click()
  await expect(studio.getByRole('button', { name: '第 1 话 0 页', exact: true })).toBeVisible()
  await expect(studio.getByRole('dialog')).toHaveCount(0)
  for (const number of [1, 2]) {
    await studio.getByRole('button', { name: '新页面', exact: true }).first().click()
    await expect(studio.getByRole('heading', { name: `第 1 话 / 第 ${number} 页`, exact: true })).toBeVisible()
    await expect(studio.getByRole('dialog')).toHaveCount(0)
  }
  const prompt = page.getByRole('textbox', { name: '向创作 Agent 提问' })
  await page.getByRole('button', { name: '生成整页', exact: true }).click()
  await expect(prompt).toHaveValue('请生成这一页的整页漫画：')
  await prompt.fill('E2E_COMIC_PAGE 生成整页漫画：雨夜站台，三格分镜，清晰对白。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(studio.getByRole('button', { name: '采用此页', exact: true })).toBeEnabled()
  await studio.getByRole('button', { name: '采用此页', exact: true }).click()
  const comic = JSON.parse((await readProjectFile(request, book.projectId, 'comic/comic.json')).content)
  const pageId = comic.episodes[0].pages[1].id
  let content = JSON.parse((await readProjectFile(request, book.projectId, `comic/pages/${pageId}/page.json`)).content)
  const firstId = content.currentId
  expect(content.results).toHaveLength(1)
  expect(comic.title).toBe('雨夜的末班车')
  expect(comic.episodes[0].pages[1]).not.toHaveProperty('title')
  expect(content).not.toHaveProperty('title')
  const canvas = await studio.locator('#pageImage').boundingBox()
  expect(canvas!.height).toBeGreaterThan(550)
  expect(await studio.getByRole('textbox').count()).toBe(0)
  const fixture = await readFile(new URL('../fixtures/comic-page.png', import.meta.url))
  const loreURL = `/api/projects/${book.projectId}/book/lore/items`
  const lore = await request.post(loreURL, { data: { id: 'detective', name: '共享侦探', type: 'character', content: 'The detective always wears a red scarf.', enabled: true } })
  expect(lore.ok(), await lore.text()).toBe(true)
  await page.getByRole('button', { name: '参考图', exact: true }).click()
  await studio.locator('#upload').setInputFiles([{ name: 'character.png', mimeType: 'image/png', buffer: fixture }, { name: 'style.png', mimeType: 'image/png', buffer: fixture }])
  await expect(studio.locator('[data-reference]')).toHaveCount(2)
  await studio.getByRole('checkbox').check()
  await studio.getByRole('button', { name: '使用所选资料', exact: true }).click()
  await expect(page.getByRole('button', { name: '参考图 3', exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '选区', exact: true }).click()
  const image = await studio.locator('#pageImage').boundingBox()
  expect(image).not.toBeNull()
  await page.mouse.move(image!.x + image!.width * .1, image!.y + image!.height * .2)
  await page.mouse.down()
  await page.mouse.move(image!.x + image!.width * .6, image!.y + image!.height * .7)
  await page.mouse.up()
  await expect(page.getByText('第 2 页 · 已选区域', { exact: true })).toBeVisible()
  await prompt.fill('E2E_COMIC_PAGE 把选区内的对白改成「再等一会儿吧」，保留其他内容。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(studio.getByRole('button', { name: '采用此页', exact: true })).toBeEnabled()
  content = JSON.parse((await readProjectFile(request, book.projectId, `comic/pages/${pageId}/page.json`)).content)
  expect(content.results).toHaveLength(2)
  expect(content.currentId).toBe(firstId)
  expect(content.results[1].sourceId).toBe(firstId)
  expect(content.results[1].selection.width).toBeGreaterThan(.4)
  expect(content.results[1].references).toHaveLength(3)
  expect(content.results[1].references[2].libraryId).toBe('detective')
  expect((await (await request.get(loreURL)).json()).items[0].content).toBe('The detective always wears a red scarf.')
  await studio.getByRole('button', { name: '对比', exact: true }).click()
  await expect(studio.getByRole('img', { name: '原图', exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '对比', exact: true }).click()
  await studio.getByRole('button', { name: '采用此页', exact: true }).click()
  await page.getByRole('textbox', { name: '向创作 Agent 提问' }).fill('E2E_COMIC_AGENT 请读取当前页。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByText('漫画页面已读取。', { exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '新页面', exact: true }).click()
  await expect(studio.getByRole('heading', { name: '第 1 话 / 第 3 页', exact: true })).toBeVisible()
  await expect(studio.getByText('这一页，等你的故事', { exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '新分话', exact: true }).click()
  await expect(studio.getByRole('button', { name: '第 2 话 0 页', exact: true })).toBeVisible()
  await expect(studio.getByRole('dialog')).toHaveCount(0)
  await studio.getByRole('button', { name: '第 2 页', exact: true }).click()
  await expect(studio.locator('#pageImage')).toBeVisible()
  await studio.getByRole('button', { name: '第 1 话 3 页', exact: true }).click()
  await expect(studio.getByRole('button', { name: '第 2 页', exact: true })).toBeHidden()
  await studio.getByRole('button', { name: '第 1 话 3 页', exact: true }).click()
  // Reordering changes position, never page identity, artwork or selection.
  const pageBeforeOutlineEdits = await readProjectFile(request, book.projectId, `comic/pages/${pageId}/page.json`)
  const from = await studio.getByRole('button', { name: '第 2 页', exact: true }).locator('img').boundingBox()
  const to = await studio.getByRole('button', { name: '第 1 页', exact: true }).boundingBox()
  const draggedRow = studio.locator(`[data-outline-id="${pageId}"]`)
  const rowBeforeDrag = await draggedRow.boundingBox()
  await page.mouse.move(from!.x + from!.width / 2, from!.y + from!.height / 2)
  await page.mouse.down()
  await page.mouse.move(to!.x + to!.width / 2 + 120, to!.y + to!.height / 2, { steps: 12 })
  // The original row moves vertically in its column, without a duplicate preview.
  await expect(studio.getByRole('button', { name: '第 2 页', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(studio.getByText('第 2 页', { exact: true })).toHaveCount(1)
  await expect(draggedRow).toHaveCSS('opacity', '1')
  await expect.poll(async () => (await draggedRow.boundingBox())!.x).toBeCloseTo(rowBeforeDrag!.x, 1)
  await expect.poll(async () => (await draggedRow.boundingBox())!.y).toBeLessThan(rowBeforeDrag!.y - 30)
  await page.screenshot({ path: 'test-results/comic-inline-drag.png', fullPage: true })
  await page.mouse.up()
  await expect(studio.getByRole('heading', { name: '第 1 话 / 第 1 页', exact: true })).toBeVisible()
  expect(JSON.parse((await readProjectFile(request, book.projectId, 'comic/comic.json')).content).episodes[0].pages[0].id).toBe(pageId)
  const pageRow = studio.getByRole('button', { name: '第 1 页', exact: true })
  await expect(draggedRow).toHaveCSS('transform', 'none')
  await pageRow.focus()
  await page.keyboard.press('Space')
  await expect(studio.locator('[aria-pressed="true"]')).toHaveCount(1)
  await page.keyboard.press('ArrowDown')
  await expect(studio.getByRole('status').filter({ hasText: '移至' })).toContainText('第 2')
  await page.keyboard.press('Space')
  await expect(studio.getByRole('heading', { name: '第 1 话 / 第 2 页', exact: true })).toBeVisible()
  // Whole episode rows remain clickable; sorting also works with a keyboard.
  await studio.getByRole('button', { name: '第 1 话 3 页', exact: true }).press('Enter')
  await expect(studio.getByRole('button', { name: '第 2 页', exact: true })).toBeHidden()
  const episodeRow = studio.getByRole('button', { name: '第 1 话 3 页', exact: true })
  await episodeRow.focus()
  await page.keyboard.press('Space')
  await expect(studio.locator('[aria-pressed="true"]')).toHaveCount(1)
  await page.keyboard.press('ArrowDown')
  await expect(studio.getByRole('status').filter({ hasText: '移至' })).toContainText('第 2')
  await page.keyboard.press('Space')
  await expect(studio.getByRole('heading', { name: '第 2 话 / 第 2 页', exact: true })).toBeVisible()
  // The next keyboard drag measures rows after the previous sort animation.
  await expect(studio.locator(`[data-outline-id="${comic.episodes[0].id}"]`)).toHaveCSS('transform', 'none')
  await studio.getByRole('button', { name: '第 2 话 3 页', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(studio.locator('[aria-pressed="true"]')).toHaveCount(1)
  await page.keyboard.press('ArrowUp')
  await expect(studio.getByRole('status').filter({ hasText: '移至' })).toContainText('第 1')
  await page.keyboard.press('Space')
  await expect(studio.getByRole('heading', { name: '第 1 话 / 第 2 页', exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '更多操作 · 第 1 话', exact: true }).click()
  await studio.getByRole('menuitem', { name: '重命名分话', exact: true }).click()
  const longTitle = '失约与重逢'.repeat(25)
  await studio.getByRole('textbox', { name: '名称', exact: true }).fill(longTitle)
  await studio.getByRole('button', { name: '保存', exact: true }).click()
  await expect(studio.getByRole('dialog')).toHaveCount(0)
  await expect(studio.getByRole('button', { name: `第 1 话 · ${longTitle} 3 页`, exact: true })).toBeVisible()
  expect(await studio.locator('body').evaluate(element => element.scrollWidth > element.clientWidth)).toBe(false)
  await studio.getByRole('button', { name: `更多操作 · 第 1 话 · ${longTitle}`, exact: true }).click()
  await studio.getByRole('menuitem', { name: '重命名分话', exact: true }).click()
  await studio.getByRole('textbox', { name: '名称', exact: true }).fill('失约')
  await studio.getByRole('button', { name: '保存', exact: true }).click()
  await studio.getByRole('button', { name: '第 1 话 · 失约 3 页', exact: true }).click()
  await studio.getByRole('button', { name: '更多操作 · 第 2 页', exact: true }).click()
  await expect(studio.getByRole('menuitem', { name: '重命名分话', exact: true })).toHaveCount(0)
  await studio.getByRole('menuitem', { name: '删除', exact: true }).click()
  await expect(studio.getByRole('heading', { name: '第 1 话 / 第 1 页', exact: true })).toBeVisible()
  await expect(studio.locator('#pageImage')).toHaveCount(0)
  await page.reload()
  await studio.getByRole('button', { name: '回收站 (1)', exact: true }).click()
  await studio.locator(`[data-trash-id="${pageId}"]`).getByRole('button', { name: '恢复', exact: true }).click()
  await expect(studio.getByText('没有已删除的分话或分页', { exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '关闭', exact: true }).click()
  await studio.getByRole('button', { name: '第 2 页', exact: true }).click()
  await expect(studio.locator('#pageImage')).toBeVisible()
  // Deleting an episode retains every page, and survives refresh before restore.
  await studio.getByRole('button', { name: '更多操作 · 第 1 话 · 失约', exact: true }).click()
  await studio.getByRole('menuitem', { name: '删除', exact: true }).click()
  await expect(studio.getByText('从第一话开始', { exact: true })).toBeVisible()
  await page.reload()
  await studio.getByRole('button', { name: '回收站 (1)', exact: true }).click()
  await studio.getByRole('button', { name: '恢复', exact: true }).click()
  await expect(studio.getByText('没有已删除的分话或分页', { exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '关闭', exact: true }).click()
  await studio.getByRole('button', { name: '第 2 页', exact: true }).click()
  await expect(studio.locator('#pageImage')).toBeVisible()
  expect((await readProjectFile(request, book.projectId, `comic/pages/${pageId}/page.json`)).content).toBe(pageBeforeOutlineEdits.content)
  await page.getByLabel('工作台侧边栏').getByRole('button', { name: '写作', exact: true }).click()
  await page.getByLabel('工作台侧边栏').getByRole('button', { name: '漫画', exact: true }).click()
  await expect(studio.locator('#pageImage')).toBeVisible()
  await page.reload()
  await studio.getByRole('button', { name: '历史', exact: true }).click()
  await expect(studio.locator('[data-version]')).toHaveCount(2)
  await studio.locator('[data-version]').last().click()
  await expect(studio.getByRole('button', { name: '采用此页', exact: true })).toBeVisible()
  await studio.getByRole('button', { name: '历史', exact: true }).click()
  await studio.locator('[data-version]').first().click()
  await expect(studio.getByRole('button', { name: '采用此页', exact: true })).toHaveCount(0)
  await expect(studio.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('漫画页面已读取。', { exact: true })).toBeVisible()
  const assets = await readdir(path.join(book.workspace, 'comic/assets/pages', pageId))
  expect(assets).toHaveLength(2)
  await page.screenshot({ path: 'test-results/comic-desktop-dark.png', fullPage: true })
  await request.patch('/api/settings', { data: { layer: 'user', changes: { language: 'en-US', theme: 'light' } } })
  await page.reload()
  const english = page.frameLocator('iframe[title="Plugin view"]')
  await expect(english.getByRole('button', { name: 'History', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/comic-desktop-light.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(english.locator('#pageImage')).toBeVisible()
  await english.getByRole('button', { name: 'Episodes & pages', exact: true }).click()
  await expect(english.getByRole('button', { name: 'Page 2', exact: true })).toBeVisible()
  await english.getByRole('button', { name: 'Page 2', exact: true }).click()
  await expect(english.getByRole('dialog')).toHaveCount(0)
  const overflow = await english.locator('body').evaluate(element => element.scrollWidth > element.clientWidth)
  expect(overflow).toBe(false)
  await page.screenshot({ path: 'test-results/comic-mobile-light.png', fullPage: true })
  await page.getByRole('button', { name: 'Creative assistant', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Message the creative Agent' })).toBeInViewport()
  await expect(english.locator('#pageImage')).toBeHidden()
  await page.screenshot({ path: 'test-results/comic-mobile-assistant.png', fullPage: true })
  await page.getByRole('button', { name: 'References 3', exact: true }).click()
  await expect(english.getByRole('dialog', { name: 'References', exact: true })).toBeVisible()
})
